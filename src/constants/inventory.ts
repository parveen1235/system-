/**
 * Loads the active inventory master list from localStorage or defaults to INITIAL_INVENTORY_MASTER.
 * Automatically synchronizes weights and packet quantities from USER_PROFILE_WEIGHT_CATALOGUE.
 */
export function getActiveInventoryMaster(): InventoryMasterItem[] {
  try {
    if (typeof window !== 'undefined' && window.localStorage) {
      const saved = window.localStorage.getItem(STORAGE_KEY_INVENTORY);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed) && parsed.length > 0) {
          // Always ensure profiles have latest catalog weights & packet quantities
          parsed.forEach((item: InventoryMasterItem) => {
            if (item.category === 'Profile') {
              const catWeight = lookupProfileWeight(item.code, item.name);
              item.weight = catWeight;
              const stripped = (item.code || '').toUpperCase().replace(/[\s\-_/.]/g, '');
              if (USER_PROFILE_WEIGHT_CATALOGUE[stripped]) {
                item.packetQty = USER_PROFILE_WEIGHT_CATALOGUE[stripped].packetQty;
              }
            }
          });

          const existingCodes = new Set(
            parsed.map((p: any) => (p.code || p.id || '').toString().trim().toUpperCase())
          );
          const missingMasters = INITIAL_INVENTORY_MASTER.filter((m) => {
            const codeKey = (m.code || m.id || '').toString().trim().toUpperCase();
            return !existingCodes.has(codeKey);
          });
          if (missingMasters.length > 0) {
            const merged = [...parsed, ...missingMasters];
            try {
              window.localStorage.setItem(STORAGE_KEY_INVENTORY, JSON.stringify(merged));
            } catch (e) {}
            return merged;
          }
          return parsed;
        }
      }
    }
  } catch (e) {
    console.error('Failed to load active inventory master from localStorage', e);
  }

  // Ensure initial master also has exact weights & packet quantities
  INITIAL_INVENTORY_MASTER.forEach((item) => {
    if (item.category === 'Profile') {
      const catWeight = lookupProfileWeight(item.code, item.name);
      item.weight = catWeight;
      const stripped = (item.code || '').toUpperCase().replace(/[\s\-_/.]/g, '');
      if (USER_PROFILE_WEIGHT_CATALOGUE[stripped]) {
        item.packetQty = USER_PROFILE_WEIGHT_CATALOGUE[stripped].packetQty;
      }
    }
  });

  return INITIAL_INVENTORY_MASTER;
}

/**
 * Searches and looks up an inventory item by code, name, and category.
 */
export function lookupInventoryItem(
  itemCode: string,
  itemName?: string,
  category?: string,
  inventoryList?: InventoryMasterItem[]
): InventoryMasterItem | undefined {
  const list = inventoryList && inventoryList.length > 0 ? inventoryList : getActiveInventoryMaster();
  if (!list || list.length === 0) return undefined;

  const rawCode = (itemCode || '').trim();
  const cleanCode = rawCode.toUpperCase();
  const strippedCode = cleanCode.replace(/[\s\-_/.]/g, '');

  // 1. Exact code match
  let found = list.find((i) => (i.code || '').trim().toUpperCase() === cleanCode);
  if (found) return found;

  // 2. Stripped/normalized code match
  if (strippedCode.length > 2) {
    found = list.find((i) => {
      const c = (i.code || '').trim().toUpperCase().replace(/[\s\-_/.]/g, '');
      return c === strippedCode;
    });
    if (found) return found;
  }

  // 3. Partial code match (e.g. SWH 60-01 in SWH-60-01-WHITE)
  found = list.find((i) => {
    const c = (i.code || '').trim().toUpperCase();
    return c.includes(cleanCode) || cleanCode.includes(c);
  });
  if (found) return found;

  // 4. Match by name or description keywords
  if (itemName) {
    const normName = itemName.toLowerCase().trim();
    found = list.find((i) => {
      const n = (i.name || '').toLowerCase();
      return n === normName || (n.length > 5 && normName.includes(n)) || (normName.length > 5 && n.includes(normName));
    });
    if (found) return found;

    // Word tokens matching (e.g. "touch lock", "friction stay 16", "cwh 60-01")
    const words = normName.split(/\s+/).filter((w) => w.length > 3);
    if (words.length > 0) {
      found = list.find((i) => {
        const n = (i.name || '').toLowerCase();
        return words.every((w) => n.includes(w));
      });
      if (found) return found;
    }
  }

  // 5. Special smart fallback for Gaskets and Weatherstrips:
  // If item code or description indicates a gasket, match any active gasket in the inventory
  const isGasketItem =
    cleanCode.includes('GKT') ||
    cleanCode.includes('GASKET') ||
    cleanCode.includes('STARG') ||
    (itemName && itemName.toLowerCase().includes('gasket'));

  if (isGasketItem) {
    const gasketItem = list.find((i) => {
      const c = (i.code || '').trim().toUpperCase();
      const n = (i.name || '').toLowerCase();
      const a = (i.application || '').toLowerCase();
      return c.includes('GKT') || c.includes('GASKET') || c.includes('STARG') || n.includes('gasket') || a.includes('gasket');
    });
    if (gasketItem) return gasketItem;
  }

  return undefined;
}

/**
 * Retrieves the effective unit rate for a cutting list item from the Inventory Master.
 * Handles unit conversion (e.g. Sq.Ft -> SQMT, Kilogram -> Meter) with automatic fallback.
 */
export interface InventoryPriceResult {
  rate: number;
  matchedItem?: InventoryMasterItem;
  fromInventory: boolean;
  originalUnit?: string;
  originalPrice?: number;
  weightPerMtr?: number;
  rateFormula?: string;
}

export function getInventoryItemPrice(
  itemCode: string,
  options?: {
    name?: string;
    category?: string;
    fallbackRate?: number;
    targetUnit?: 'Mtr' | 'SQMT' | 'Pcs' | 'CAN' | 'Pair' | 'Set' | string;
    inventoryList?: InventoryMasterItem[];
    isProfile?: boolean;
    profileType?: 'outer' | 'sash' | 'mullion' | 'bead';
  }
): InventoryPriceResult {
  const fallback = options?.fallbackRate ?? 0;
  const matched = lookupInventoryItem(itemCode, options?.name, options?.category, options?.inventoryList);

  if (!matched || typeof matched.price !== 'number' || isNaN(matched.price) || matched.price < 0) {
    return { rate: fallback, fromInventory: false };
  }

  let rate = matched.price;
  let weightPerMtr: number | undefined;
  let rateFormula: string | undefined;

  // 1. Profile handling (uPVC Profiles in ₹/KG, Aluminium Guide Rail in ₹/Meter)
  if (matched.category === 'Profile' || options?.isProfile) {
    const isGuideRail =
      matched.code === 'DURON-GR' ||
      matched.name?.toLowerCase().includes('guide rail') ||
      matched.rmCategory === 'GUIDE RAIL';

    if (isGuideRail || matched.unit === 'Meter') {
      // Aluminium Guide Rail inside sliding systems is measured and billed in METERS
      rate = matched.price;
      rateFormula = `₹${rate}/Mtr (एल्युमिनियम गाइड रेल)`;
    } else if (matched.unit === 'Kilogram') {
      const catalogWeight = lookupProfileWeight(matched.code, matched.name, options?.profileType);
      const weight = matched.weight || catalogWeight;
      weightPerMtr = weight;
      if (options?.targetUnit === 'KG') {
        rate = matched.price;
        rateFormula = `₹${matched.price}/KG (भार दर)`;
      } else {
        rate = Math.round(matched.price * weight * 100) / 100;
        rateFormula = `₹${matched.price}/Kg × ${weight} Kg/m = ₹${rate}/m`;
      }
    } else {
      rate = matched.price;
      rateFormula = `₹${rate}/m (प्रति मीटर दर)`;
    }
  }

  // 2. Glazing handling (Sq.Ft as primary standard or SQMT conversion)
  else if (matched.category === 'Glass' || options?.targetUnit === 'SQMT' || options?.targetUnit === 'Sq.Ft') {
    if (options?.targetUnit === 'SQMT') {
      if (matched.unit === 'Sq.Ft') {
        rate = Math.round(matched.price * 10.7639 * 10) / 10;
        rateFormula = `₹${matched.price}/Sq.Ft × 10.764 = ₹${rate}/m²`;
      } else {
        rate = matched.price;
        rateFormula = `₹${rate}/m²`;
      }
    } else {
      // Default to Sq.Ft pricing since user configures glass rates in Sq.Ft
      if ((matched.unit as string) === 'sq mtr' || (matched.unit as string) === 'SQMT') {
        rate = Math.round((matched.price / 10.76391) * 100) / 100;
        rateFormula = `₹${matched.price}/m² ÷ 10.764 = ₹${rate}/Sq.Ft`;
      } else {
        rate = matched.price;
        rateFormula = `₹${rate}/Sq.Ft`;
      }
    }
  }

  // 3. Hardware, Screws, Gaskets, Installation: Rate is per unit
  else {
    rate = matched.price;
    rateFormula = `₹${rate}/${matched.unit || 'Unit'}`;
  }

  if (matched.price === 0) {
    rateFormula = `₹0.00 (इन्वेंट्री दर ₹0)`;
  }

  return {
    rate: Math.max(0, rate),
    matchedItem: matched,
    fromInventory: true,
    originalUnit: matched.unit,
    originalPrice: matched.price,
    weightPerMtr,
    rateFormula,
  };
}
